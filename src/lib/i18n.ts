/**
 * Website languages. English lives at the root (/safaris), Norwegian under /no (/no/safaris).
 * Text editors write in the admin is translated there; this file holds the fixed interface text.
 */

export const LANGS = ['en', 'no'] as const
export type Lang = (typeof LANGS)[number]

export const isLang = (v: unknown): v is Lang => LANGS.includes(v as Lang)

/** Value for <html lang> and hreflang: Norwegian Bokmål. */
export const HTML_LANG: Record<Lang, string> = { en: 'en', no: 'nb' }
export const DATE_LOCALE: Record<Lang, string> = { en: 'en-GB', no: 'nb-NO' }

/** Prefixes a site path with the language, e.g. ('no', '/safaris') → '/no/safaris'. */
export const localePath = (lang: Lang, path: string) => (lang === 'en' ? path : path === '/' ? `/${lang}` : `/${lang}${path}`)

/** Removes a language prefix: '/no/safaris' → '/safaris'. */
export const stripLang = (pathname: string) => pathname.replace(/^\/(no|en)(?=\/|$)/, '') || '/'

